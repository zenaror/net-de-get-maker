#!/usr/bin/env python3
"""Emit a compact 3x5 uppercase/digit tile font as RGBDS source."""

import pathlib
import sys

GLYPHS = {
    "A": ("010", "101", "111", "101", "101"),
    "B": ("110", "101", "110", "101", "110"),
    "C": ("011", "100", "100", "100", "011"),
    "D": ("110", "101", "101", "101", "110"),
    "E": ("111", "100", "110", "100", "111"),
    "F": ("111", "100", "110", "100", "100"),
    "G": ("011", "100", "101", "101", "011"),
    "H": ("101", "101", "111", "101", "101"),
    "I": ("111", "010", "010", "010", "111"),
    "J": ("001", "001", "001", "101", "010"),
    "K": ("101", "101", "110", "101", "101"),
    "L": ("100", "100", "100", "100", "111"),
    "M": ("10001", "11011", "10101", "10001", "10001"),
    "N": ("101", "111", "111", "101", "101"),
    "O": ("010", "101", "101", "101", "010"),
    "P": ("110", "101", "110", "100", "100"),
    "Q": ("010", "101", "101", "111", "011"),
    "R": ("110", "101", "110", "101", "101"),
    "S": ("011", "100", "010", "001", "110"),
    "T": ("111", "010", "010", "010", "010"),
    "U": ("101", "101", "101", "101", "111"),
    "V": ("101", "101", "101", "101", "010"),
    "W": ("10001", "10101", "10101", "10101", "01010"),
    "X": ("101", "101", "010", "101", "101"),
    "Y": ("101", "101", "010", "010", "010"),
    "Z": ("111", "001", "010", "100", "111"),
    "0": ("111", "101", "101", "101", "111"),
    "1": ("010", "110", "010", "010", "111"),
    "2": ("110", "001", "010", "100", "111"),
    "3": ("110", "001", "010", "001", "110"),
    "4": ("101", "101", "111", "001", "001"),
    "5": ("111", "100", "110", "001", "110"),
    "6": ("011", "100", "110", "101", "010"),
    "7": ("111", "001", "010", "010", "010"),
    "8": ("010", "101", "010", "101", "010"),
    "9": ("010", "101", "011", "001", "110"),
}


def tile(rows):
    pixels = [0] * 8
    if rows:
        for y, row in enumerate(rows, start=1):
            pixels[y] = sum((ch == "1") << (7 - (x + 2)) for x, ch in enumerate(row))
    out = []
    for row in pixels:
        out.extend((row, 0))  # low plane, high plane: palette index 1 foreground
    return out


def main():
    out = pathlib.Path(sys.argv[1])
    data = [0] * 16  # tile 0 is the space glyph
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789":
        data.extend(tile(GLYPHS[ch]))
    lines = ["FontTiles:"]
    for start in range(0, len(data), 16):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in data[start:start + 16]))
    lines.append("FontTilesEnd:")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
